create table if not exists public.it_activity_codes (
  code text primary key,
  title text not null,          -- краткое название, полный текст — в приказе № 449
  segment text not null,
  sort integer not null
);
alter table public.it_activity_codes enable row level security;
drop policy if exists it_codes_read on public.it_activity_codes;
create policy it_codes_read on public.it_activity_codes for select using (active_profile());
drop policy if exists it_codes_owner on public.it_activity_codes;
create policy it_codes_owner on public.it_activity_codes for all using (is_owner()) with check (is_owner());

